/**
 * @h1w0rld/dsh-recovery-resume v0.2.0 —— форк dsh-recovery-resume (flandre2233, 0.1.3),
 * доделан под DSH 0.1.7-rc.2 (format v4).
 *
 * ЧТО ДОБАВЛЕНО относительно базы (base design: только live-агенты):
 *   БУТ-АКТИВАЦИЯ холодных сессий. База ждала, пока сессию кто-нибудь откроет
 *   (агенты в DSH создаются лениво, после рестарта agent/created не стреляет,
 *   и «зависшая» сессия могла висеть неделями). Здесь после старта хоста
 *   сканируются холодные сессии с оборванным хвостом (открытый ход или
 *   turn/end reason=interrupted) и активируются штатным швом
 *   ctx.agents.resume({resumeSessionId, agentOptions, setup}) — тем же,
 *   каким пользуется официальный session-controller:
 *     - resumeWith() самой фабрики сам дописывает interrupted-closers открытому ходу
 *       (repair-on-resume), после чего базовая логика inspectTail видит готовый хвост;
 *     - setup реплицирует composeAgent контроллера: installModelSelection +
 *       presets.mount (если preset есть в observation).
 *   Дальше работает НЕИЗМЕННАЯ логика базы: agent/created → consider →
 *   inspectTail → леджер/бэкофф → agent.followup() с русским промптом.
 *
 * Оставлено как в базе (осознанно): user stop (aborted/user) — финал, не продолжаем;
 * перманентные ошибки (AUTH/QUOTA/контекст) — не продолжаем; 429/сеть — продолжаем
 * с бэкоффом; живой ход не трогаем.
 */

